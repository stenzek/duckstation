static int LeadIndex(unsigned char b)
{
  if (b >= 0x81 && b <= 0x9F)
    return b - 0x81;

  if (b >= 0xE0 && b <= 0xFC)
    return 31 + (b - 0xE0);

  return -1;
}

static int TrailIndex(unsigned char b)
{
  if (b >= 0x40 && b <= 0x7E)
    return b - 0x40;

  if (b >= 0x80 && b <= 0xFC)
    return 63 + (b - 0x80);

  return -1;
}

std::string ShiftJIS::ConvertShiftJISToUTF8(std::string_view str)
{
  std::string out;
  out.reserve(str.size());

  std::size_t i = 0;
  while (i < str.size())
  {
    const auto b = static_cast<unsigned char>(str[i]);

    // zero terminates string
    if (b == 0)
      break;

    char32_t cp;

    if (b <= 0x7F)
    {
      // These three round-trip control mappings are part of ICU's ibm-943_P15A-2003 table.
      if (b == 0x1A)
        cp = 0x001C;
      else if (b == 0x1C)
        cp = 0x007F;
      else if (b == 0x7F)
        cp = 0x001A;
      else
        cp = b;

      i++;
    }
    else if (b >= 0xA1 && b <= 0xDF)
    {
      cp = 0xFF61u + (b - 0xA1u);
      i++;
    }
    else
    {
      const int lead = LeadIndex(b);
      if (lead < 0)
      {
        StringUtil::EncodeAndAppendUTF8(out, StringUtil::UNICODE_REPLACEMENT_CHARACTER);
        i++;
        continue;
      }

      if ((str.size() - i) < 2)
      {
        StringUtil::EncodeAndAppendUTF8(out, StringUtil::UNICODE_REPLACEMENT_CHARACTER);
        i++;
        continue;
      }

      const auto b2 = static_cast<unsigned char>(str[i + 1]);
      if (b2 == 0)
      {
        StringUtil::EncodeAndAppendUTF8(out, StringUtil::UNICODE_REPLACEMENT_CHARACTER);
        break;
      }

      const int trail = TrailIndex(b2);
      if (trail < 0)
      {
        StringUtil::EncodeAndAppendUTF8(out, StringUtil::UNICODE_REPLACEMENT_CHARACTER);
        i += 2;
        continue;
      }

      cp = kDoubleByteToUnicode[static_cast<std::size_t>(lead) * 188u + static_cast<std::size_t>(trail)];
      if (cp == 0)
      {
        StringUtil::EncodeAndAppendUTF8(out, StringUtil::UNICODE_REPLACEMENT_CHARACTER);
        i += 2;
        continue;
      }

      i += 2;
    }

    StringUtil::EncodeAndAppendUTF8(out, cp);
  }

  return out;
}

std::string ShiftJIS::ConvertFullWidthToASCII(std::string_view str)
{
  std::string out;
  out.reserve(str.size());

  for (size_t offset = 0; offset < str.size();)
  {
    char32_t cp;
    offset += StringUtil::DecodeUTF8(str, offset, &cp);

    // IDEOGRAPHIC SPACE -> ASCII space.
    if (cp == 0x3000)
    {
      cp = ' ';
    }
    // FULLWIDTH ! through ~ -> ASCII ! through ~.
    else if (cp >= 0xFF01 && cp <= 0xFF5E)
    {
      cp -= 0xFEE0;
    }

    StringUtil::EncodeAndAppendUTF8(out, cp);
  }

  return out;
}
